from django.core.validators import MinValueValidator, MaxLengthValidator
from decimal import Decimal
from django.core.exceptions import ValidationError
from core.models import AttributedRecord
from django.db import models
from django.utils import timezone

def validate_birth_date(value):
    if value > timezone.localdate():
        raise ValidationError("Date of birth cannot be in the future.")


class Patient(AttributedRecord):
    class SexAssignedAtBirth(models.TextChoices):
        UNKNOWN = "unknown", "Unknown / Not recorded"
        FEMALE = "female", "Female"
        MALE = "male", "Male"
        INTERSEX = "intersex", "Intersex"

    full_name = models.CharField(max_length=200)

    sex_assigned_at_birth = models.CharField(
        max_length=10,
        choices=SexAssignedAtBirth.choices,
        default=SexAssignedAtBirth.UNKNOWN,
        verbose_name="Sex assigned at birth",
    )


    date_of_birth = models.DateField(
        null=True,
        blank=True,
        validators=[validate_birth_date],
    )

    height_cm = models.DecimalField(max_digits=5, decimal_places=2, null=True, blank=True,
        validators=[MinValueValidator(Decimal('0.01'))],
        help_text='Optional recorded height in cm. No unit conversion is performed.')
    height_measured_on = models.DateField(null=True, blank=True, validators=[validate_birth_date])
    weight_kg = models.DecimalField(max_digits=6, decimal_places=2, null=True, blank=True,
        validators=[MinValueValidator(Decimal('0.01'))],
        help_text='Optional recorded weight in kg. No unit conversion is performed.')
    weight_measured_on = models.DateField(null=True, blank=True, validators=[validate_birth_date])
    medications = models.TextField(blank=True, max_length=5000, validators=[MaxLengthValidator(5000)],
        help_text='User-reported medications. Blank means not recorded, not no medications.')
    medications_as_of = models.DateField(null=True, blank=True, validators=[validate_birth_date])
    underlying_conditions = models.TextField(blank=True, max_length=5000, validators=[MaxLengthValidator(5000)],
        help_text='User-reported conditions, not a diagnosis generated by this application.')
    conditions_as_of = models.DateField(null=True, blank=True, validators=[validate_birth_date])

    def clean(self):
        super().clean()
        errors = {}
        for value_field, date_field in (
            ('height_cm', 'height_measured_on'), ('weight_kg', 'weight_measured_on'),
            ('medications', 'medications_as_of'), ('underlying_conditions', 'conditions_as_of'),
        ):
            value = getattr(self, value_field)
            date = getattr(self, date_field)
            present = bool(value.strip()) if isinstance(value, str) else value is not None
            if date and not present:
                errors[date_field] = 'A date requires a recorded value.'
            if date and self.date_of_birth and date < self.date_of_birth:
                errors[date_field] = 'Date cannot be before the date of birth.'
        if errors:
            raise ValidationError(errors)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at", "-pk"]

    def __str__(self):
        return f"{self.full_name} (#{self.pk})"